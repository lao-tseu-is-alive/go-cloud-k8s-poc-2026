// Goéland POC - Case tasks (spec v2 §28).
//
// Proto-first definition for TaskService + supporting messages. A task is work
// to do on a case, independent of any workflow: created by an operator today,
// later by a circulation, a workflow or an AI proposal (origin). It belongs to
// its case (it is not a subject) and its audit events are written on the CASE
// subject in the same transaction.
//
// A task is assigned to one internal user or one org unit, or to nobody yet;
// every (re)assignment is kept as history. Completing or cancelling a task
// records a SYSTEM entry in the case timeline. A closed case freezes its tasks
