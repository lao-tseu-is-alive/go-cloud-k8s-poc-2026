// Goéland POC - Case circulations (spec v2 §29).
//
// Proto-first definition for CirculationService + supporting messages. A
// circulation sends a case to several recipients (internal users or org
// units) for their answer. It is a light orchestration of tasks: each
// recipient gets a task (origin CIRCULATION) when its step opens; recipients
// of one step answer in parallel and the next step opens once the previous one
// has fully answered.
//
// Every response completes the recipient's task and is recorded as a locked
// RESPONSE entry in the case timeline; the last response completes the
// circulation with a SYSTEM summary entry. A circulation belongs to its case
// and is audited on the CASE subject; a closed case freezes it.

