// Goéland POC - Grants and security groups (spec v2 §32, roadmap GLD-048).
//
// Proto-first definition for AccessService. Every subject (case, document,
// actor, thing, org unit, group) may carry grants: a level (READ < CONTRIBUTE <
// MANAGE < FULL_CONTROL) given to an internal user, a security group or an org
// unit (a unit grant covers its sub-units). The effective level of a user is the
// most specific one: personal grant, then the highest grant of the user's
// groups, then the grant of the nearest unit, then an application role covering
// the subject's kind (ADMIN covers every kind), then the baseline — READ unless
// the subject is confidential (confidentiality_level >= 2), where neither roles
// nor the baseline apply. There is no deny level. A change or a revocation keeps
// the grant as history and is audited on the subject; a subject never loses its
