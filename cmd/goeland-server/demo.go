// demoSeedTimeout bounds a whole generation.
const demoSeedTimeout = 30 * time.Minute

// demoSeedBaseURL is the base URL of the in-process requests: nothing listens
// on it, the transport hands each request to the handler directly.
const demoSeedBaseURL = "http://demo-seed.invalid"

// authModeDemo is the demo authentication mode (GOELAND_AUTH_MODE=demo, GLD-085).
const authModeDemo = "demo"

// authModeSeed is the auth mode of the in-process server of demo-seed: the
// demo users of a Session, never read from the environment.
const authModeSeed = "demo-seed"

// errNotDemoDatabase refuses the demo authentication mode on a database that
// demo-seed did not generate.
var errNotDemoDatabase = errors.New("GOELAND_AUTH_MODE=demo lets anyone sign in without a password: it serves only a database generated by `goeland-server demo-seed` (no demo_dataset row here)")

// errNotBrandNew refuses a database that already holds subjects.
var errNotBrandNew = errors.New("the database already holds data: demo-seed only writes into a brand-new database")

// demoSeedMain runs `goeland-server demo-seed` and returns the exit code: it
// generates the synthetic demo data (GLD-079, docs/DEMO_SCRIPT.md) through the
// API of a server built in this process for the demo users only, which never
// listens on a network.
func demoSeedMain(args []string) int {
	flags := flag.NewFlagSet("demo-seed", flag.ContinueOnError)
	profile := flags.String("profile", demodata.ProfileSmall, "amount of data: "+strings.Join(demodata.Profiles(), ", "))
	lang := flags.String("lang", "fr", "language of the generated texts: "+strings.Join(demodata.Languages(), ", "))
	if err := flags.Parse(args); err != nil {
		return 2
	}
	config, err := loadConfig()
	if err != nil {
		fmt.Fprintln(os.Stderr, "goeland-server demo-seed configuration error:", err)
		return 1
	}
	log := slog.New(slog.NewJSONHandler(os.Stderr, &slog.HandlerOptions{Level: config.LogLevel}))
	log.Info("goeland demo-seed", "app", version.AppName, "version", version.Version, "profile", *profile, "lang", *lang)
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	ctx, cancel := context.WithTimeout(ctx, demoSeedTimeout)
	defer cancel()
	report, err := runDemoSeed(ctx, config, demodata.Options{Profile: *profile, Language: *lang}, log)
	if report.Counts != nil {
		report.Print(os.Stdout)
	}
	if err != nil {
		log.Error("demo-seed failed", "error", err)
		return 1
	}
	return 0
}

// runDemoSeed builds the application with the demo users' verifier and their
// administrator bootstrapped, checks that the database is brand new, and
// generates the data through the in-process API. The requests are logged at
// warning level only: thousands of them would drown the report.
func runDemoSeed(ctx context.Context, config serverConfig, opts demodata.Options, log *slog.Logger) (demodata.Report, error) {
	session, err := demodata.NewSession()
	if err != nil {
		return demodata.Report{}, err
	}
	// Whatever the configured auth mode, only the demo users act, and only the
	// demo administrator is bootstrapped (never a dev user made admin).
	config.AuthMode, config.DevUserAdmin = authModeSeed, false
	config.tokenVerifier = session.Verifier()
	config.BootstrapAdmins = []string{demodata.AdminUserID()}
	quiet := slog.New(slog.NewJSONHandler(os.Stderr, &slog.HandlerOptions{Level: max(config.LogLevel, slog.LevelWarn)}))
	app, err := newApplication(ctx, config, quiet)
	if err != nil {
		return demodata.Report{}, err
	}
	defer app.close()
	if err := ensureBrandNew(ctx, app.pool); err != nil {
		return demodata.Report{}, err
	}
	clients := session.NewClients(&http.Client{Transport: handlerTransport{app.handler}}, demoSeedBaseURL)
	ownerURL := config.demoOwnerURL
	if ownerURL == "" {
		ownerURL = config.DatabaseURL
	}
	return generateDemo(ctx, clients, ownerURL, opts, log)
}

// generateDemo writes the demo through clients while a story clock records
// its steps, then, as the schema owner, re-dates the generated history to the
// story times and marks the database as a demo.
func generateDemo(ctx context.Context, clients *demodata.Clients, ownerURL string, opts demodata.Options, log *slog.Logger) (demodata.Report, error) {
	owner, err := pgxpool.New(ctx, ownerURL)
	if err != nil {
		return demodata.Report{}, fmt.Errorf("connect as the schema owner: %w", err)
	}
	defer owner.Close()
	clock := &storyClock{pool: owner}
	opts.Clock = clock.mark
	started := time.Now()
	// The stories read at story times months apart within seconds: record every read.
	report, err := demodata.Generate(core.WithEveryAccessLogged(ctx), clients, opts)
	log.Info("demo data written", "duration", time.Since(started).Round(time.Millisecond), "story_steps", len(clock.marks))
	if err != nil {
		return report, err
	}
	if err := redateDemo(ctx, owner, clock.marks); err != nil {
		return report, fmt.Errorf("re-date the demo history: %w", err)
	}
	return report, markDemoDataset(ctx, owner, report)
}

// demoDataset is the marker row demo-seed writes once the demo is generated.
type demoDataset struct {
	// Profile is the generator profile of the demo (small or demo).
	Profile string
	// Language is the language of the generated texts.
	Language string
}

// markDemoDataset records that the database holds the generated demo, which
// lets the demo authentication mode serve it.
func markDemoDataset(ctx context.Context, pool *pgxpool.Pool, report demodata.Report) error {
	_, err := pool.Exec(ctx, `INSERT INTO demo_dataset (profile, language, generator_version) VALUES ($1, $2, $3)`,
		report.Profile, report.Language, version.Version)
	if err != nil {
		return fmt.Errorf("mark the demo database: %w", err)
	}
	return nil
}

// prepareDatabase migrates or verifies the schema, then, in demo mode, reads
// the demo marker into config or refuses the database (GLD-085).
func prepareDatabase(ctx context.Context, config *serverConfig, pool *pgxpool.Pool, log *slog.Logger) error {
	if err := prepareSchema(ctx, config.DBMigrate, pool, log); err != nil {
		return err
	}
	if config.AuthMode != authModeDemo {
		return nil
	}
	demo, err := requireDemoDataset(ctx, pool)
	if err != nil {
		return err
	}
	config.demo = demo
	log.Warn("demo authentication mode: anyone can sign in as a demo user, on this generated demo database only",
		"profile", demo.Profile, "language", demo.Language)
	return nil
}

// requireDemoDataset reads the demo marker, or refuses a database without it.
func requireDemoDataset(ctx context.Context, pool *pgxpool.Pool) (*demoDataset, error) {
	var d demoDataset
	err := pool.QueryRow(ctx, `SELECT profile, language FROM demo_dataset`).Scan(&d.Profile, &d.Language)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, errNotDemoDatabase
	}
	if err != nil {
		return nil, fmt.Errorf("read the demo marker: %w", err)
	}
	return &d, nil
}

// frontendDemoUser is a demo user as GET /config lists it in demo mode.
type frontendDemoUser struct {
	// Key names the user in the demo script and the SPA messages.
	Key string `json:"key"`
	// ID is the application user id.
	ID string `json:"id"`
	// DisplayName is the user's name.
	DisplayName string `json:"displayName"`
	// Email is the user's fictional e-mail address.
	Email string `json:"email"`
	// Token is the user's public bearer token in demo mode.
	Token string `json:"token"`
}

// frontend is the demo block of GET /config: the dataset and the demo users
// with their public tokens.
func (d *demoDataset) frontend() map[string]any {
	users := make([]frontendDemoUser, 0, len(demodata.Users()))
	for _, u := range demodata.Users() {
		users = append(users, frontendDemoUser{
			Key: u.Key, ID: strconv.FormatInt(u.ID, 10), DisplayName: u.DisplayName, Email: u.Email, Token: demodata.PublicToken(u.Key),
		})
	}
	return map[string]any{"profile": d.Profile, "language": d.Language, "users": users}
}

// ensureBrandNew refuses a database holding any subject: the demo never mixes
// with other data, real or not.
func ensureBrandNew(ctx context.Context, pool *pgxpool.Pool) error {
	var used bool
	if err := pool.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM subject_ref)`).Scan(&used); err != nil {
		return fmt.Errorf("check that the database is brand new: %w", err)
	}
	if used {
		return errNotBrandNew
	}
	return nil
}

// handlerTransport is an http.RoundTripper serving each request with a
// handler of this process, as a server would after reading it.
type handlerTransport struct{ handler http.Handler }

// RoundTrip serves req with the handler and returns the recorded response.
func (t handlerTransport) RoundTrip(req *http.Request) (*http.Response, error) {
	in := req.Clone(req.Context())
	in.RequestURI = req.URL.RequestURI()
	in.RemoteAddr = "127.0.0.1:0"
	if in.Body == nil {
		in.Body = http.NoBody
	}
	recorder := httptest.NewRecorder()
	t.handler.ServeHTTP(recorder, in)
	resp := recorder.Result()
	resp.Request = req
	return resp, nil
}
